#!/usr/bin/env python3
"""
scripts/commit-msg-guard.py
Cổng kiểm soát Thông điệp Commit & MR (Clean Commit & AI Attribution Guard).

Mục tiêu cốt lõi (Theo quy tắc cứng §0 AGENTS.md):
1. Không AI Attribution: Nghiêm cấm mọi hình thức 'Co-Authored-By', 'Generated with', 'Generated by', 'Assisted by'.
2. Không Model / Tool Names: Nghiêm cấm nhắc đến tên mô hình (Claude, ChatGPT, Gemini, Copilot, GPT-4, Cursor, DeepSeek).
3. Tập trung vào thay đổi: Message commit chỉ mô tả thay đổi kỹ thuật thuần túy theo chuẩn Conventional Commits.

Thoát:
  0: Thông điệp commit hoàn toàn sạch và chuẩn mực (PASS).
  1: Phát hiện vi phạm quy tắc commit (BLOCKED).
"""

import re
import sys
from pathlib import Path

FORBIDDEN_ATTRIBUTION_PATTERNS = [
    re.compile(r"co-authored-by\s*:", re.IGNORECASE),
    re.compile(r"generated\s+(?:with|by)\b", re.IGNORECASE),
    re.compile(r"assisted\s+by\b", re.IGNORECASE),
    re.compile(r"\b(?:claude|chatgpt|openai|gemini|copilot|antigravity|qoder|kilo\s+code)\b", re.IGNORECASE),
    re.compile(r"\b(?:gpt-?4|gpt-?3\.5|claude-?3|sonnet|opus|haiku|deepseek)\b", re.IGNORECASE),
]


def audit_commit_message(msg: str) -> list[str]:
    violations = []
    if not msg or not msg.strip():
        return ["Thông điệp commit không được để trống."]

    for line_no, line in enumerate(msg.splitlines(), 1):
        for pat in FORBIDDEN_ATTRIBUTION_PATTERNS:
            m = pat.search(line)
            if m:
                violations.append(
                    f"Dòng {line_no} [FORBIDDEN_AI_ATTRIBUTION] Chứa từ khóa bị cấm: '{m.group(0)}'. "
                    "Quy tắc cứng: Message commit chỉ mô tả thay đổi kỹ thuật; không Co-Authored-By, không tên model/AI."
                )
    return violations


def main():
    import argparse
    parser = argparse.ArgumentParser(description="Clean Commit & AI Attribution Guard")
    parser.add_argument("message_or_file", help="Chuỗi thông điệp commit hoặc đường dẫn tệp chứa message (COMMIT_EDITMSG)")
    args = parser.parse_args()

    target = args.message_or_file
    p = Path(target)
    if p.is_file():
        try:
            msg = p.read_text(encoding="utf-8", errors="replace")
        except Exception as exc:
            print(f"Lỗi đọc file commit message: {exc}", file=sys.stderr)
            sys.exit(1)
    else:
        msg = target

    violations = audit_commit_message(msg)
    if violations:
        print("❌ [COMMIT MSG GUARD - VI PHẠM QUY TẮC COMMIT]")
        for v in violations:
            print(f"  - {v}")
        sys.exit(1)
    else:
        print("✅ [COMMIT MSG GUARD] Thông điệp commit 100% sạch và hợp chuẩn.")
        sys.exit(0)


if __name__ == "__main__":
    main()
