#!/usr/bin/env python3
"""
scripts/sync-adapters.py
Generate tool-specific files from the single source of truth:
  agents/roles/*.md  ->  .kilo/agents/<name>.md        (Kilo Code custom agents)
                     ->  .agents/rules/role-<name>.md  (Antigravity rules)
  AGENTS.md          ->  GEMINI.md, CODEX.md, .github/copilot-instructions.md, .agents/rules/agents-core.md

Usage:
  python scripts/sync-adapters.py          # write generated files
  python scripts/sync-adapters.py --check  # report drift, exit 1 if any
"""

import sys
