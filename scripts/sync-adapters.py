def yq(text) -> str:
    r"""Quote a string as a YAML/JSON-compatible double-quoted scalar.

    Escapes backslash, double quote, newline, carriage return, tab and other control
    characters, so patterns such as a real newline before "git push" or a Windows path
    like .\mvnw.cmd never break the YAML front matter of the generated files.
    """
    out = []
    for ch in str(text):
        if ch == '\\':
            out.append('\\\\')
        elif ch == '"':
            out.append('\\"')
        elif ch == '\n':
            out.append('\\n')
        elif ch == '\r':
            out.append('\\r')
        elif ch == '\t':
            out.append('\\t')
        elif ord(ch) < 0x20:
            out.append('\\x%02x' % ord(ch))
        else:
            out.append(ch)
    return '"' + ''.join(out) + '"'


_KILO_RULE_LINE = re.compile(r'^\s{4}"(?:[^"\\\x00-\x1f]|\\["\\ntr]|\\x[0-9a-f]{2})*": (?:allow|deny|ask)$')


def validate_kilo_frontmatter(text: str, rel: str) -> list:
    """Strict structural check of the front matter we emit: no raw control characters, every rule line well formed."""
    problems = []
    m = re.match(r'^---\n(.*?)\n---\n', text, re.S)
    if not m:
        return [f"{rel}: missing front matter"]
    seen = set()
    for i, line in enumerate(m.group(1).split('\n'), 2):
        if not line.startswith('    "'):
            seen = set()
        if re.search(r'[\x00-\x08\x0b-\x1f]', line):
            problems.append(f"{rel}:{i}: control character in front matter")
        if line.startswith('    "'):
            if not _KILO_RULE_LINE.match(line):
                problems.append(f"{rel}:{i}: malformed rule line: {line[:70]}")
            else:
                key = line.rsplit(': ', 1)[0]
                if key in seen:
                    problems.append(f"{rel}:{i}: duplicate mapping key {key.strip()[:60]}")
                seen.add(key)
    return problems


def dedupe_rule_lines(lines: list) -> list:
    """Drop repeated pattern keys inside each permission mapping, keeping the LAST occurrence.

    Kilo evaluates rules with "last match wins", and strict YAML readers reject duplicate mapping
    keys, so a key that appears twice must appear once, at the position and with the action of its last use.
    """
    out = []
    block = []

    def flush():
        seen = {}
        for ln in block:
            key = ln.rsplit(': ', 1)[0]
            if key in seen:
                seen.pop(key)
            seen[key] = ln
        out.extend(seen.values())
        block.clear()

    for ln in lines:
        if ln.startswith('    "'):
            block.append(ln)
        else:
            flush()
            out.append(ln)
    flush()
    return out


def norm(text: str) -> str:
    return text.replace('\r\n', '\n')


def split_front_matter(text: str):
    t = norm(text)
    m = re.match(r'(?s)^---\n(.*?)\n---\n(.*)$', t)
    if not m:
        raise ValueError('missing front matter')
    return m.group(1), m.group(2)


def parse_meta(front: str) -> dict:
    meta = {}
    cur = None
    for line in front.splitlines():
        m_item = re.match(r'^\s+-\s+(.+)$', line)
        if m_item:
            if cur:
                if not isinstance(meta[cur], list):
                    meta[cur] = []
                meta[cur].append(m_item.group(1).strip().strip('"'))
            continue
        m_key = re.match(r'^([a-z_]+):\s*(.*)$', line)
        if m_key:
            cur = m_key.group(1)
            val = m_key.group(2).strip()
            meta[cur] = [] if val == '' else val
    return meta


def get_list(meta: dict, key: str) -> list:
    val = meta.get(key, [])
    if isinstance(val, list):
        return val
    return [val] if val else []


def build_kilo(meta: dict, body: str, src_rel: str) -> str:
    allow = get_list(meta, 'edit_allow')
    deny = get_list(meta, 'edit_deny')
    desc = str(meta.get('description', ''))

    lines = ['---', f'description: {yq(desc)}', f"mode: {meta.get('mode', '')}"]

    role_name = meta.get('name', '')
    model_to_use = role_models.get(role_name)
    if not model_to_use and 'model_tier' in meta:
        tier = meta['model_tier']
        if tier not in ('strong', 'standard', 'fast'):
            raise ValueError(f"role {src_rel} has invalid model_tier: {tier} (use strong, standard or fast)")
        if tier_models.get(tier):
            model_to_use = tier_models[tier]

    if model_to_use:
        lines.append(f"model: {model_to_use}")

    lines.append('permission:')
    if not allow:
        lines.append('  edit: deny')
    else:
        lines.append('  edit:')
        if '*' not in allow:
            lines.append('    "*": deny')
        # Kilo matches edit patterns against path.relative(worktree, file), which on
        # Windows uses backslashes (tasks\T-01.md), so emit a backslash twin for each.
        for a in allow:
            for p in dict.fromkeys([a, a.replace('/', '\\')]):
                lines.append(f'    {yq(p)}: allow')
        for d in deny:
            for p in dict.fromkeys([d, d.replace('/', '\\')]):
                lines.append(f'    {yq(p)}: deny')

    bash = meta.get('bash')
    if bash == 'none':
        lines.append('  bash: deny')
    elif bash == 'readonly':
        lines.append('  bash:')
        lines.append('    "*": deny')
        ro_cmds = [
            'git status*', 'git diff*', 'git log*', 'git show*', 'git blame*',
            'git ls-files*', 'git rev-parse*', 'git branch --list*', 'git branch -a*',
            'git branch -v*', 'git merge-base*', 'git rev-list*', 'git shortlog*',
            'git grep*'
        ]
        for c in ro_cmds:
            lines.append(f'    {yq(c)}: allow')
        for c in get_list(meta, 'bash_allow'):
            lines.append(f'    {yq(c)}: allow')
        chain_deny = ['*;*', '*&&*', '*||*', '*|*', '*\n*', '*\\n*']
        for c in (chain_deny + git_write_deny + danger_deny + get_list(meta, 'bash_deny')):
            lines.append(f'    {yq(c)}: deny')
    elif bash == 'full':
        extra_ask = get_list(meta, 'bash_ask')
        extra_deny = list(get_list(meta, 'bash_deny'))
        if role_name != 'researcher':
            extra_deny.insert(0, '*scripts/gemini-research*')
        lines.append('  bash:')
        lines.append('    "*": allow')
        for c in (danger_ask + extra_ask + git_commit_ask):
            lines.append(f'    {yq(c)}: ask')
        for c in (git_hard_deny + danger_deny + extra_deny):
            lines.append(f'    {yq(c)}: deny')
        for c in git_read_allow:
            lines.append(f'    {yq(c)}: allow')
    else:
        raise ValueError(f"role {src_rel} has invalid bash value: {bash} (use none, readonly or full)")

    web = meta.get('web', 'deny')
    if web not in ('allow', 'ask', 'deny'):
        raise ValueError(f"role {src_rel} has invalid web value: {web} (use allow, ask or deny)")
    for k in ('webfetch', 'websearch', 'codesearch'):
        lines.append(f'  {k}: {web}')

    lines = dedupe_rule_lines(lines)
    lines.append('---')
    lines.append(f'<!-- {MARKER} from {src_rel}. Do not edit. -->')
    lines.append(ANTI_LOOP_PROMPT.strip() + '\n')
    lines.append(body.rstrip('\n') + '\n')
    return '\n'.join(lines)


