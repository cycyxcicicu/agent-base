def toml_ml(text: str) -> str:
    """TOML multi-line string. Dùng chuỗi literal ''' (không xử lý escape, an toàn với đường dẫn Windows); nếu thân có ''' thì
    chuyển sang chuỗi thường \"\"\" và escape."""
    if "'''" not in text:
        return "'''\n" + text.rstrip('\n') + "\n'''"
    esc = text.rstrip('\n').replace('\\', '\\\\').replace('"""', '""\\"')
    return '"""\n' + esc + '\n"""'


