def sweep_stale(root: Path, outputs: dict, check: bool = False) -> int:
    """Xóa (hoặc báo, khi check) file sinh mồ côi trong các thư mục adapter."""
    problems = 0
    for dir_rel, pat in (('.kilo/agents', '*.md'), ('.agents/rules', '*.md'), ('.claude/agents', '*.md'),
                         ('.codex/agents', '*.toml'), ('.qoder/agents', '*.md'), ('.qoder/rules', '*.md')):
        dir_full = root / dir_rel
        if not dir_full.exists():
            continue
        for f in dir_full.glob(pat):
            rel = f"{dir_rel}/{f.name}"
            if rel in outputs:
                continue
            try:
                f_text = f.read_text(encoding='utf-8')
            except UnicodeDecodeError:
                print(f"SKIP     {rel}: không đọc được UTF-8")
                continue
            if MARKER in f_text:
                if check:
                    print(f"STALE    {rel}")
                    problems += 1
                else:
                    f.unlink()
                    print(f"removed  {rel}")
    return problems


