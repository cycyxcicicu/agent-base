def yq(text) -> str:
    """Quote a string as a YAML/JSON-compatible double-quoted scalar.

    Escapes backslash, double quote, newline, carriage return, tab and other control
    characters, so patterns such as a real newline before "git push" or a Windows path
    like .\mvnw.cmd never break the YAML front matter of the generated files.
    """
    out = []
    for ch in str(text):
        if ch == '\\':
            out.append('\\\\')
        elif ch == '"':
            out.append('\\"')
        elif ch == '\n':
            out.append('\\n')
        elif ch == '\r':
            out.append('\\r')
        elif ch == '\t':
            out.append('\\t')
        elif ord(ch) < 0x20:
            out.append('\\x%02x' % ord(ch))
        else:
            out.append(ch)
    return '"' + ''.join(out) + '"'


_KILO_RULE_LINE = re.compile(r'^\s{4}"(?:[^"\\\x00-\x1f]|\\["\\ntr]|\\x[0-9a-f]{2})*": (?:allow|deny|ask)$')


def validate_kilo_frontmatter(text: str, rel: str) -> list:
    """Strict structural check of the front matter we emit: no raw control characters, every rule line well formed."""
    problems = []
    m = re.match(r'^---\n(.*?)\n---\n', text, re.S)
    if not m:
        return [f"{rel}: missing front matter"]
    seen = set()
    for i, line in enumerate(m.group(1).split('\n'), 2):
        if not line.startswith('    "'):
            seen = set()
        if re.search(r'[\x00-\x08\x0b-\x1f]', line):
            problems.append(f"{rel}:{i}: control character in front matter")
        if line.startswith('    "'):
            if not _KILO_RULE_LINE.match(line):
                problems.append(f"{rel}:{i}: malformed rule line: {line[:70]}")
            else:
                key = line.rsplit(': ', 1)[0]
                if key in seen:
                    problems.append(f"{rel}:{i}: duplicate mapping key {key.strip()[:60]}")
                seen.add(key)
    return problems


def dedupe_rule_lines(lines: list) -> list:
    """Drop repeated pattern keys inside each permission mapping, keeping the LAST occurrence.

    Kilo evaluates rules with "last match wins", and strict YAML readers reject duplicate mapping
    keys, so a key that appears twice must appear once, at the position and with the action of its last use.
    """
    out = []
    block = []

    def flush():
        seen = {}
        for ln in block:
            key = ln.rsplit(': ', 1)[0]
            if key in seen:
                seen.pop(key)
            seen[key] = ln
        out.extend(seen.values())
        block.clear()

    for ln in lines:
        if ln.startswith('    "'):
            block.append(ln)
        else:
            flush()
            out.append(ln)
    flush()
    return out


def norm(text: str) -> str:
    return text.replace('\r\n', '\n')


def split_front_matter(text: str):
    t = norm(text)
    m = re.match(r'(?s)^---\n(.*?)\n---\n(.*)$', t)
    if not m:
        raise ValueError('missing front matter')
    return m.group(1), m.group(2)


def parse_meta(front: str) -> dict:
    meta = {}
    cur = None
    for line in front.splitlines():
        m_item = re.match(r'^\s+-\s+(.+)$', line)
        if m_item:
            if cur:
                if not isinstance(meta[cur], list):
                    meta[cur] = []
                meta[cur].append(m_item.group(1).strip().strip('"'))
            continue
        m_key = re.match(r'^([a-z_]+):\s*(.*)$', line)
        if m_key:
            cur = m_key.group(1)
            val = m_key.group(2).strip()
            meta[cur] = [] if val == '' else val
    return meta


def get_list(meta: dict, key: str) -> list:
    val = meta.get(key, [])
    if isinstance(val, list):
        return val
    return [val] if val else []


def build_kilo(meta: dict, body: str, src_rel: str) -> str:
    allow = get_list(meta, 'edit_allow')
    deny = get_list(meta, 'edit_deny')
    desc = str(meta.get('description', ''))

    lines = ['---', f'description: {yq(desc)}', f"mode: {meta.get('mode', '')}"]

    role_name = meta.get('name', '')
    model_to_use = role_models.get(role_name)
    if not model_to_use and 'model_tier' in meta:
        tier = meta['model_tier']
        if tier not in ('strong', 'standard', 'fast'):
            raise ValueError(f"role {src_rel} has invalid model_tier: {tier} (use strong, standard or fast)")
        if tier_models.get(tier):
            model_to_use = tier_models[tier]

    if model_to_use:
        lines.append(f"model: {model_to_use}")

    lines.append('permission:')
    if not allow:
        lines.append('  edit: deny')
    else:
        lines.append('  edit:')
        if '*' not in allow:
            lines.append('    "*": deny')
        for a in allow:
            lines.append(f'    {yq(a)}: allow')
        for d in deny:
            lines.append(f'    {yq(d)}: deny')

    bash = meta.get('bash')
    if bash == 'none':
        lines.append('  bash: deny')
    elif bash == 'readonly':
        lines.append('  bash:')
        lines.append('    "*": deny')
        ro_cmds = [
            'git status*', 'git diff*', 'git log*', 'git show*', 'git blame*',
            'git ls-files*', 'git rev-parse*', 'git branch --list*', 'git branch -a*',
            'git branch -v*', 'git merge-base*', 'git rev-list*', 'git shortlog*',
            'git grep*'
        ]
        for c in ro_cmds:
            lines.append(f'    {yq(c)}: allow')
        for c in get_list(meta, 'bash_allow'):
            lines.append(f'    {yq(c)}: allow')
        chain_deny = ['*;*', '*&&*', '*||*', '*|*', '*\n*', '*\\n*']
        for c in (chain_deny + git_write_deny + danger_deny + get_list(meta, 'bash_deny')):
            lines.append(f'    {yq(c)}: deny')
    elif bash == 'full':
        extra_ask = get_list(meta, 'bash_ask')
        extra_deny = list(get_list(meta, 'bash_deny'))
        if role_name != 'researcher':
            extra_deny.insert(0, '*scripts/gemini-research*')
        lines.append('  bash:')
        lines.append('    "*": allow')
        for c in (danger_ask + extra_ask + git_commit_ask):
            lines.append(f'    {yq(c)}: ask')
        for c in (git_write_deny + danger_deny + extra_deny):
            lines.append(f'    {yq(c)}: deny')
        for c in git_read_allow:
            lines.append(f'    {yq(c)}: allow')
    else:
        raise ValueError(f"role {src_rel} has invalid bash value: {bash} (use none, readonly or full)")

    web = meta.get('web', 'deny')
    if web not in ('allow', 'ask', 'deny'):
        raise ValueError(f"role {src_rel} has invalid web value: {web} (use allow, ask or deny)")
    for k in ('webfetch', 'websearch', 'codesearch'):
        lines.append(f'  {k}: {web}')

    lines = dedupe_rule_lines(lines)
    lines.append('---')
    lines.append(f'<!-- {MARKER} from {src_rel}. Do not edit. -->')
    lines.append(body.rstrip('\n') + '\n')
    return '\n'.join(lines)


def main():
    outputs = {}
    roles_dir = ROOT / 'agents' / 'roles'
    role_files = sorted(list(roles_dir.glob('*.md')), key=lambda x: x.name)

    for f in role_files:
        src_rel = f"agents/roles/{f.name}"
        front, body = split_front_matter(f.read_text(encoding='utf-8'))
        meta = parse_meta(front)

        for k in ('name', 'description', 'mode', 'bash'):
            if not meta.get(k):
                raise ValueError(f"role {src_rel} is missing '{k}'")

        if meta['name'] != f.stem:
            raise ValueError(f"role {src_rel}: name '{meta['name']}' does not match file name")

        outputs[f".kilo/agents/{meta['name']}.md"] = build_kilo(meta, body, src_rel)
        outputs[f".agents/rules/role-{meta['name']}.md"] = f"<!-- {MARKER} from {src_rel}. Do not edit. -->\n" + body

    agents_md = norm((ROOT / 'AGENTS.md').read_text(encoding='utf-8'))
    outputs['GEMINI.md'] = f"<!-- {MARKER} from AGENTS.md. Do not edit. -->\n" + agents_md
    outputs['CODEX.md'] = f"<!-- {MARKER} from AGENTS.md. Do not edit. -->\n" + agents_md
    outputs['.github/copilot-instructions.md'] = f"<!-- {MARKER} from AGENTS.md. Do not edit. -->\n" + agents_md
    outputs['.agents/rules/agents-core.md'] = f"<!-- {MARKER} from AGENTS.md. Do not edit. -->\n" + agents_md

    # Generate .claude/settings.json to enforce deny rules on Claude Code
    # Use tool specifiers Bash(...) and PowerShell(...) strictly; no bare strings
    claude_deny = [f"Bash({c})" for c in (git_write_deny + danger_deny)] + [f"PowerShell({c})" for c in (git_write_deny + danger_deny)]
    claude_ask = [f"Bash({c})" for c in (danger_ask + git_commit_ask)] + [f"PowerShell({c})" for c in (danger_ask + git_commit_ask)]
    claude_settings = {
        "$schema": "https://json.schemastore.org/claude-code-settings.json",
        "permissions": {
            "deny": claude_deny,
            "ask": claude_ask
        }
    }
    outputs['.claude/settings.json'] = json.dumps(claude_settings, indent=2, ensure_ascii=False) + '\n'

    problems = 0
    for rel, content in outputs.items():
        full = ROOT / rel
        new_text = norm(content)

        if rel.startswith('.kilo/agents/'):
            for msg in validate_kilo_frontmatter(new_text, rel):
                print(f"INVALID  {msg}")
                problems += 1

        if rel.startswith('.agents/rules/') and len(new_text) > ANTIGRAVITY_LIMIT:
            print(f"WARNING: {rel} is {len(new_text)} chars, over Antigravity rule limit of {ANTIGRAVITY_LIMIT}")
            problems += 1

        if CHECK:
            if not full.exists():
                print(f"MISSING  {rel}")
                problems += 1
            elif norm(full.read_text(encoding='utf-8')) != new_text:
                print(f"OUTDATED {rel}")
                problems += 1
        else:
            full.parent.mkdir(parents=True, exist_ok=True)
            full.write_text(new_text, encoding='utf-8')
            print(f"wrote    {rel}")

    # Check for stale files
    for dir_rel in ('.kilo/agents', '.agents/rules'):
        dir_full = ROOT / dir_rel
        if not dir_full.exists():
            continue
        for f in dir_full.glob('*.md'):
            rel = f"{dir_rel}/{f.name}"
            if rel in outputs:
                continue
            f_text = f.read_text(encoding='utf-8')
            if MARKER in f_text:
                if CHECK:
                    print(f"STALE    {rel}")
                    problems += 1
                else:
                    f.unlink()
                    print(f"removed  {rel}")

    if CHECK:
        if problems > 0:
            print(f"FAIL: {problems} problem(s). Run python scripts/sync-adapters.py to regenerate.")
            sys.exit(1)
        print("OK: generated files are up to date.")
    elif problems > 0:
        sys.exit(1)


if __name__ == '__main__':
    main()
